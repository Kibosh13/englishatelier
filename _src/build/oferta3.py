def T(head, rows):
    th = "<thead><tr>" + "".join(f"<th>{E(h)}</th>" for h in head) + "</tr></thead>" if head else ""
    return '<div class="tbl"><table>' + th + "<tbody>" + "".join("<tr>" + "".join(f"<td>{E(c)}</td>" for c in r) + "</tr>" for r in rows) + "</tbody></table></div>"

